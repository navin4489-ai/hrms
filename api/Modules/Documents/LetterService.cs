using Microsoft.EntityFrameworkCore;
using Wintech.Hrms.Api.Common.Auditing;
using Wintech.Hrms.Api.Common.CurrentUser;
using Wintech.Hrms.Api.Common.ErrorHandling;
using Wintech.Hrms.Api.Common.Files;
using Wintech.Hrms.Api.Common.Registration;
using Wintech.Hrms.Api.Common.Time;
using Wintech.Hrms.Api.Data;
using Wintech.Hrms.Api.Domain.Approvals;
using Wintech.Hrms.Api.Domain.Documents;

namespace Wintech.Hrms.Api.Modules.Documents;

/// <summary>
/// Letter requests (contract §11, FR-EMP-071/072). Requests are routed through the central
/// approval engine with RequestType "Letter"; the PDF is generated by
/// <see cref="LetterApprovalHandler"/> when the workflow completes.
/// </summary>
public interface ILetterService : IAppService
{
    Task<IReadOnlyList<LetterRequestDto>> GetMineAsync(CancellationToken cancellationToken = default);
    Task<CreateLetterResponse> CreateAsync(CreateLetterRequest request, CancellationToken cancellationToken = default);
    Task<FileDownload> DownloadAsync(Guid id, CancellationToken cancellationToken = default);
}

public sealed class LetterService : ILetterService
{
    /// <summary>The single approval transaction type served by <see cref="LetterApprovalHandler"/>.</summary>
    public const string LetterRequestType = "Letter";

    public static readonly IReadOnlyList<string> AllowedLetterTypes =
        ["EmploymentCertificate", "SalaryCertificate", "ExperienceLetter", "AddressProof"];

    private readonly AppDbContext _db;
    private readonly ICurrentUser _currentUser;
    private readonly IAuditService _audit;
    private readonly IClock _clock;
    private readonly IPrivateFileStore _files;
    private readonly IServiceProvider _serviceProvider;

    public LetterService(AppDbContext db, ICurrentUser currentUser, IAuditService audit, IClock clock,
        IPrivateFileStore files, IServiceProvider serviceProvider)
    {
        _db = db;
        _currentUser = currentUser;
        _audit = audit;
        _clock = clock;
        _files = files;
        _serviceProvider = serviceProvider;
    }

    public async Task<IReadOnlyList<LetterRequestDto>> GetMineAsync(CancellationToken cancellationToken = default)
    {
        _currentUser.EnsureActive();
        var employeeId = RequireEmployeeId();

        var rows = await _db.Set<LetterRequest>().AsNoTracking()
            .Where(r => r.EmployeeId == employeeId)
            .OrderByDescending(r => r.CreatedAt)
            .ToListAsync(cancellationToken);

        return rows.Select(r => new LetterRequestDto(
            r.Id, r.LetterType, r.Purpose, r.Status, r.CreatedAt, r.ApprovalTaskId, r.GeneratedDocumentId)).ToList();
    }

    public async Task<CreateLetterResponse> CreateAsync(CreateLetterRequest request, CancellationToken cancellationToken = default)
    {
        _currentUser.EnsureActive();
        var employeeId = RequireEmployeeId();

        if (!AllowedLetterTypes.Contains(request.LetterType, StringComparer.Ordinal))
            throw new RequestValidationException(errors: new()
            {
                ["letterType"] = [$"Allowed values: {string.Join(", ", AllowedLetterTypes)}."]
            });

        var letter = new LetterRequest
        {
            Id = Guid.NewGuid(),
            EmployeeId = employeeId,
            LetterType = request.LetterType,
            Purpose = request.Purpose.Trim(),
            Notes = string.IsNullOrWhiteSpace(request.Notes) ? null : request.Notes.Trim(),
            Status = LetterRequestStatus.Pending,
            CreatedAt = _clock.UtcNow
        };
        _db.Set<LetterRequest>().Add(letter);

        // Route through the central approval engine (WF-LETTER: HR review).
        // The Approvals module owns the implementation; when it is not yet present the
        // request stays Pending without a task so the rest of the module keeps working.
        var approvals = _serviceProvider.GetService<IApprovalService>();
        ApprovalTask? task = null;
        if (approvals is not null)
        {
            task = await approvals.StartAsync(new ApprovalStartRequest(
                LetterRequestType,
                letter.Id,
                $"{LetterTypeLabel(letter.LetterType)} request — {_currentUser.DisplayName}",
                _currentUser.RequireUserId(),
                employeeId,
                _currentUser.DisplayName), cancellationToken);
            letter.ApprovalTaskId = task.Id;
        }

        _audit.Add("LetterRequest.Create", "LetterRequest", letter.Id.ToString(),
            details: new { letter.LetterType, letter.Purpose, ApprovalTaskId = letter.ApprovalTaskId });
        await _db.SaveChangesAsync(cancellationToken);

        return new CreateLetterResponse(letter.Id, letter.ApprovalTaskId, letter.Status.ToString());
    }

    public async Task<FileDownload> DownloadAsync(Guid id, CancellationToken cancellationToken = default)
    {
        _currentUser.EnsureActive();
        var employeeId = RequireEmployeeId();

        var letter = await _db.Set<LetterRequest>().AsNoTracking()
            .FirstOrDefaultAsync(r => r.Id == id && r.EmployeeId == employeeId, cancellationToken)
            ?? throw new NotFoundException("The requested letter was not found.");

        if (letter.Status != LetterRequestStatus.Generated || letter.GeneratedDocumentId is null)
            throw new ConflictException("The letter has not been generated yet. It becomes downloadable once the request is approved.");

        var document = await _db.Set<EmployeeDocument>().AsNoTracking()
            .FirstOrDefaultAsync(d => d.Id == letter.GeneratedDocumentId, cancellationToken)
            ?? throw new NotFoundException("The generated letter is no longer available.");

        var stream = await _files.OpenReadAsync(document.StorageKey, cancellationToken);

        await _audit.RecordAsync("LetterRequest.Download", "LetterRequest", letter.Id.ToString(),
            details: new { letter.LetterType, DocumentId = document.Id }, cancellationToken: cancellationToken);

        return new FileDownload(stream.Content, stream.ContentType, document.Name);
    }

    internal static string LetterTypeLabel(string letterType) => letterType switch
    {
        "SalaryCertificate" => "Salary certificate",
        "ExperienceLetter" => "Experience letter",
        "AddressProof" => "Address proof letter",
        _ => "Employment certificate"
    };

    private Guid RequireEmployeeId() =>
        _currentUser.EmployeeId
        ?? throw new ForbiddenException("No employee record is linked to your account.");
}
